const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const manifest=read('app/src/main/AndroidManifest.xml');
const gradle=read('app/build.gradle');
const base='app/src/main/java/club/sanai/app/';
const main=read(base+'MainActivity.java');
const updater=read(base+'UpdateCenter.java');
const alert=read(base+'ChadAlert.java');
const rest=read(base+'RestReceiver.java');
const html=read('app/src/main/assets/index.html');
assert(!/REQUEST_INSTALL_PACKAGES|SYSTEM_ALERT_WINDOW|UpdateFileProvider/.test(manifest));
assert(/applicationId 'club.sanai.app'/.test(gradle));
assert(/targetSdk 35; versionCode 74; versionName '6.4.7'/.test(gradle));
for(const setting of ['setAllowFileAccess(false)','setAllowFileAccessFromFileURLs(false)','setAllowUniversalAccessFromFileURLs(false)','MIXED_CONTENT_NEVER_ALLOW'])assert(main.includes(setting),setting);
assert(main.includes('file:///android_asset/index.html'));
assert(!/evaluateJavascript|canRequestPackageInstalls|ACTION_MANAGE_UNKNOWN_APP_SOURCES|HttpURLConnection/.test(updater));
assert(updater.includes('https://github.com/2645chounggs-dot/SANAI-CLUB/releases'));
assert(!alert.includes('TYPE_APPLICATION_OVERLAY'));
assert(!rest.includes('canDrawOverlays'));
assert(html.includes("connect-src https://world.openfoodfacts.org https://search.openfoodfacts.org"));
assert(html.includes('V6.4.7'));
console.log('Security source assertions passed; device and signed APK tests are still required.');
