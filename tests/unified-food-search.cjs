'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx={window:{}};vm.createContext(ctx);
new vm.Script(fs.readFileSync('app/src/main/assets/sanai-unified-search.js','utf8')).runInContext(ctx);
const S=ctx.window.SanaiFoodSearch;
const food=(name,extra={})=>({name,base:100,unit:'g',kcal:120,p:24,c:1,f:2,...extra});
const chicken=food('닭가슴살'),estimate=food('닭가슴살',{estimate:true,source:'추정'}),label=food('수비드림 닭가슴살',{brand:'수비드림',alias:'수비드',source:'제품 라벨'}),official=food('닭가슴살',{officialImport:true,source:'공공 식품영양성분 DB'});
assert.equal(S.score(chicken,'닭 가슴살'),120);
assert.equal(S.score(chicken,'ㄷㄱㅅㅅ'),55);
assert.equal(S.score(chicken,'닭가슴샬'),0);
assert.equal(S.score(chicken,'닭가슴샬',{fuzzy:true}),30);
assert(S.score(label,'수비드림 닭가슴살')>0);
assert.equal(S.score(food('돈가스'),'돈카츠'),120);
assert.equal(S.ranked([label,estimate,official],'닭가슴살')[0].officialImport,true);
assert.equal(S.ranked([label,chicken],'없는메뉴',{fuzzy:true}).length,0);
const header=['식품코드','식품명','영양성분함량 기준량','에너지(kcal)','단백질(g)','탄수화물(g)','지방(g)','제조사명','출처명','데이터생성일자','식품중량'];
const rows=[header,['A1','닭가슴살','100 g','120','24','1','2','테스트제조사','식품의약품안전처','2026-01-01','150 g'],['B2','누락 제품','100g','100','','1','2','','','',''],['C3','비정상 제품','100g','100','999','1','2','','','',''],['D4','다른 제품','50 g','60','12','0.5','1','','농촌진흥청','','50 g']];
const imported=S.parseRows(rows);assert.equal(imported.length,2);
assert.equal(imported[0].portion,150);assert.equal(imported[0].foodCode,'A1');assert(imported[0].source.includes('식품의약품안전처'));
assert.equal(imported[1].base,50);
assert.throws(()=>S.parseRows([header,rows[2]]));
const existing=[food('기존 사용자 DB')];const merged=S.merge(existing,imported);assert.equal(merged.length,3);
assert.equal(S.merge(merged,imported).length,3);assert.equal(existing.length,1);
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
assert(html.includes('sanai-unified-search.js')&&html.includes('id="n-csv"')&&html.includes('data-n="google-food"'));
assert(html.includes("store.get('imported')")&&html.includes('SanaiFoodSearch.merge(op.result,data)'));
assert(html.includes('SanaiNative.searchFoodProducts')&&html.includes("JSON.parse(new TextDecoder().decode(bytes))"));
const main=fs.readFileSync('app/src/main/java/club/sanai/app/MainActivity.java','utf8');
assert(main.includes('new java.net.URL("https://search.openfoodfacts.org/search")'));
assert(main.includes('setInstanceFollowRedirects(false)')&&main.includes('Base64.NO_WRAP')&&main.includes('1024*1024'));
assert(main.includes('setAllowUniversalAccessFromFileURLs(false)'));
