'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const ota=fs.readFileSync('ota/patch.js','utf8');
function snackModule(source){
 const begin=source.indexOf('(function sanaiSnackRecommendations(){');
 assert(begin>=0,'snack module absent');
 const end=source.indexOf('\n})();',begin);
 assert(end>begin,'snack module end absent');
 return source.slice(begin,end+6);
}
const moduleHtml=snackModule(html),moduleOta=snackModule(ota);
assert.equal(moduleHtml.replaceAll('V6.4.6','V6.4.4'),moduleOta,'Native bundle and OTA must use the same recommendation implementation apart from APK version guard');
new vm.Script(moduleHtml);
const builtStart=html.indexOf('const nBuilt=['),builtEnd=html.indexOf('// V5.3 외식 검색',builtStart);
assert(builtStart>0&&builtEnd>builtStart);
const built=vm.runInNewContext(html.slice(builtStart,builtEnd)+'\nnBuilt');
const choiceStart=moduleHtml.indexOf('const choices=['),choiceEnd=moduleHtml.indexOf('const labels=',choiceStart);
assert(choiceStart>0&&choiceEnd>choiceStart);
const choices=new Function(moduleHtml.slice(choiceStart,choiceEnd)+'\nreturn choices;')();
const functionsStart=moduleHtml.indexOf('function buildChoices(){'),functionsEnd=moduleHtml.indexOf('function addNote(',functionsStart);
assert(functionsStart>0&&functionsEnd>functionsStart);
const buildFn=new Function('choices','nBuilt','nProteinFood','nValidFood','nTotals',moduleHtml.slice(functionsStart,functionsEnd)+'\nreturn {buildChoices,snackScore};');
const configuredWhey={name:'내 프로틴',base:30,unit:'g',kcal:115,p:22,c:3,f:2};
const totals=rows=>rows.reduce((a,x)=>{for(const k of ['kcal','p','c','f'])a[k]+=x[k]*x.amount/x.base;return a;},{kcal:0,p:0,c:0,f:0});
const validate=x=>x&&typeof x.name==='string'&&x.base>0&&['kcal','p','c','f'].every(k=>Number.isFinite(x[k]));
const {buildChoices,snackScore}=buildFn(choices,built,()=>configuredWhey,validate,totals);
const options=buildChoices();
assert.equal(options.length,choices.length,'Every suggestion must resolve to an existing food entry');
assert(options.every(x=>x.items.every(y=>validate(y.food)&&y.amount>0)));
const whey=options.find(x=>x.name==='프로틴 1스쿱');
const banana=options.find(x=>x.name==='바나나 1개');
assert.equal(whey.total.p,22,'Configured protein label must override default');
assert.equal(whey.total.kcal,115);
const goals={p:142,c:213,f:57};
const lowProtein={p:60,c:210,f:55};
assert(snackScore(whey,lowProtein,goals,['p'])>snackScore(banana,lowProtein,goals,['p']),'Protein deficit should prioritize protein-rich snacks');
const lowCarb={p:142,c:80,f:57};
assert(snackScore(banana,lowCarb,goals,['c'])>snackScore(whey,lowCarb,goals,['c']),'Carb deficit should prioritize carb-rich snacks');
const lowFat={p:142,c:213,f:12};
const almond=options.find(x=>x.name==='아몬드 한 줌');
assert(snackScore(almond,lowFat,goals,['f'])>snackScore(banana,lowFat,goals,['f']),'Fat deficit should prioritize fat-rich snacks');
assert(moduleHtml.includes("meal:'간식'")&&moduleHtml.includes('nSave(')&&moduleHtml.includes('data-sanai-snack'),'One-tap logging must remain wired to local nutrition storage');
console.log('Smart snack recommendations smoke tests PASS');
